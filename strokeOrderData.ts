export function getTrueStrokeOrderGlyph(char: string): TrueStrokeGlyph | null {
  // 1. Direct Latin / digit / punctuation
  const latin = LATIN_GLYPHS[char];
  if (latin) {
    return {
      strokes: latin.s,
      advance: latin.w,
      script: 'latin',
    };
  }

  // 2. Japanese Hiragana & Katakana (177 verified AnimCJK kana)
  const kana = KANA_STROKE_DATA[char];
  if (kana) {
    const isSmall = /[ぁぃぅぇぉっゃゅょゎァィゥェォッャュョヮ]/.test(char);
    return {
      strokes: kana.map((s) => s.map(([x, y]) => [x, y] as [number, number])),
      advance: isSmall ? 0.72 : 0.90,
      script: 'kana',
    };
  }

  // 3. Korean Hangul Syllable & Jamo (Mathematical decomposition of all 11,172 Hangul syllables)
  const hangul = composeHangulSyllable(char);
  if (hangul) {
    return hangul;
  }

  // 4. Chinese Hanzi & Japanese Kanji (Preloaded from hanzi-writer-data via /api/stroke-medians)
  const hanzi = hanziClientCache.get(char);
  if (hanzi && hanzi.length > 0) {
    return {
      strokes: hanzi.map((s) => s.map(([x, y]) => [x, y] as [number, number])),
      advance: 0.98,
      script: 'cjk',
    };
  }

  return null;
}
