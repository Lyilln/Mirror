const RIGHT_VOWELS = new Set(['ㅏ', 'ㅐ', 'ㅑ', 'ㅒ', 'ㅓ', 'ㅔ', 'ㅕ', 'ㅖ', 'ㅣ']);
const BOTTOM_VOWELS = new Set(['ㅗ', 'ㅛ', 'ㅜ', 'ㅠ', 'ㅡ']);

function composeHangulSyllable(ch: string): TrueStrokeGlyph | null {
  const code = ch.codePointAt(0) ?? 0;
  if (code >= 0x3131 && code <= 0x3163) {
    const paths = getConsonantPaths(ch, 0.12, 0.12, 0.76, 0.76);
    if (paths.length > 0) {
      return { strokes: paths, advance: 0.94, script: 'hangul' };
    }
    return {
      strokes: placeInRect(BASIC_JAMO[ch] ?? [], 0.12, 0.12, 0.76, 0.76),
      advance: 0.94,
      script: 'hangul',
    };
  }
  if (code < 0xac00 || code > 0xd7a3) return null;

  const sIndex = code - 0xac00;
  const choIdx = Math.floor(sIndex / 588);
  const jungIdx = Math.floor((sIndex % 588) / 28);
  const jongIdx = sIndex % 28;

  const cho = CHO_LIST[choIdx];
  const jung = JUNG_LIST[jungIdx];
  const jong = JONG_LIST[jongIdx];
  const hasJong = jongIdx > 0;
  const strokes: Array<Array<[number, number]>> = [];

  if (RIGHT_VOWELS.has(jung)) {
    const topH = hasJong ? 0.56 : 0.84;
    const topY = hasJong ? 0.06 : 0.08;
    strokes.push(...getConsonantPaths(cho, 0.08, topY + 0.04, 0.44, topH - 0.06));
    strokes.push(...placeInRect(BASIC_JAMO[jung] ?? [], 0.54, topY, 0.38, topH));
  } else if (BOTTOM_VOWELS.has(jung)) {
    const choH = hasJong ? 0.34 : 0.46;
    const vY = hasJong ? 0.40 : 0.54;
    const vH = hasJong ? 0.22 : 0.36;
    strokes.push(...getConsonantPaths(cho, 0.18, 0.06, 0.64, choH));
    strokes.push(...placeInRect(BASIC_JAMO[jung] ?? [], 0.10, vY, 0.80, vH));
  } else {
    // Mixed medial vowel (ㅗ/ㅜ/ㅡ under initial + vertical wing on right)
    const parts = COMPOUND_VOWEL_PARTS[jung] ?? ['ㅗ', 'ㅣ'];
    const cH = hasJong ? 0.32 : 0.44;
    const horizY = hasJong ? 0.38 : 0.52;
    const horizH = hasJong ? 0.22 : 0.34;
    const wingH = hasJong ? 0.56 : 0.84;
    strokes.push(...getConsonantPaths(cho, 0.10, 0.06, 0.48, cH));
    strokes.push(...placeInRect(BASIC_JAMO[parts[0]] ?? [], 0.08, horizY, 0.58, horizH));
    strokes.push(...placeInRect(BASIC_JAMO[parts[1]] ?? [], 0.66, 0.06, 0.28, wingH));
  }

  if (hasJong && jong) {
    strokes.push(...getConsonantPaths(jong, 0.14, 0.64, 0.72, 0.30));
  }

  return strokes.length > 0 ? { strokes, advance: 0.96, script: 'hangul' } : null;
}

