import { KANA_STROKE_DATA } from './kanaStrokeData';

export interface TrueStrokeGlyph {
  strokes: Array<Array<[number, number]>>; // Normalized coordinates: X centered around 0, Y top->down [-0.5..+0.5]
  advance: number; // Optical horizontal advance in em-units (1.0 = full square CJK em-box)
  script: 'latin' | 'cjk' | 'hangul' | 'kana';
}

const hanziClientCache = new Map<string, number[][][] | null>();

export async function preloadStrokeMediansForText(text: string): Promise<void> {
  const cjkChars = Array.from(text).filter(
    (ch) => /^[\u3400-\u9FFF\uF900-\uFAFF]$/.test(ch) && !hanziClientCache.has(ch),
  );
  if (cjkChars.length === 0) return;

  try {
    const res = await fetch('/api/stroke-medians', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ chars: Array.from(new Set(cjkChars)) }),
    });
    if (!res.ok) return;
    const data = (await res.json()) as { medians?: Record<string, number[][][]> };
    const found = data.medians ?? {};
    for (const ch of cjkChars) {
      if (Array.isArray(found[ch]) && found[ch].length > 0) {
        hanziClientCache.set(ch, found[ch]);
      } else {
        hanziClientCache.set(ch, null);
      }
    }
  } catch {
    // Allow fallback to glyph contour if network temporarily unavailable
  }
}

